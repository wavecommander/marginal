import UIKit

// Plain text, Markdown, HTML and web archives → PDF. The document is laid out by the off-screen
// web renderer on the app's 6 × 9 inch page at the chosen text size, with the same margins and
// base style sheet as EPUB (`EPUBStyle`), printed in segments when long, and joined with an
// outline from its headings and its links. See docs/FORMAT_IMPORT_PLAN.md, "Text, Markdown,
// HTML".
//
// Decisions the plan left open:
// - Plain text and Markdown are set in the app's typography (`TextDocumentStyle`). An HTML file
//   or web archive keeps its own CSS; the same typography applies only where its CSS says
//   nothing (zero-specificity `:where()` rules), and the text size is the root size its
//   relative sizes scale from (sizes it fixes in px stay as they are).
// - Plain text: see `PlainTextHTML` (encoding, paragraphs, hard wrapping, laid-out text).
// - Markdown: see `MarkdownHTML`.
// - HTML: only the file itself was imported, so pictures, style sheets and frames beside it are
//   missing; pictures inside it as `data:` URLs show. Missing pictures are replaced by their
//   description (alt text) or left out. An `.xhtml` file that is not well-formed XML is laid out
//   as HTML instead.
// - Web archive: see `WebArchiveResources`.
// - Title: the HTML `<title>`, else the first `h1` (Markdown: its first `#` heading); plain text
//   has none (the file name is used).
// - Outline: every visible `h1`–`h6`, nested by level, each on the page that shows its text.

/// Turns plain text, Markdown, HTML and web archives into a PDF on the app's reflow page.
nonisolated struct TextDocumentConverter: DocumentConverter {
    var version: Int { 1 }
    var formats: Set<ImportFormat> { [.plainText, .markdown, .html, .webArchive] }
    /// Seconds the document may take to load before the conversion fails.
    var loadTimeout: TimeInterval = 60
    var diagnostics: WebConversionDiagnostics?
    var trace: (@Sendable (String) -> Void)?

    func convert(_ input: ConversionInput, progress: @escaping @Sendable (Double) -> Void) async throws -> ConvertedDocument {
        try await WebConversion.run(input, noun: "document") { workspace in
            let source = try await Self.prepare(input)
            progress(0.05)
            let rendered = try await TextDocumentPrinter.print(
                source, textSize: input.options.textSize, workspace: workspace, timeout: loadTimeout,
                diagnostics: diagnostics, trace: trace, progress: { progress(0.05 + 0.8 * $0) })
            try Task.checkCancellation()
            let pageCount = try await WebConversion.assemble(rendered.parts, outline: .headings, title: rendered.title,
                                                             output: input.outputURL, diagnostics: diagnostics,
                                                             progress: { progress(0.85 + 0.15 * $0) })
            progress(1)
            return ConvertedDocument(pdf: input.outputURL, pageCount: pageCount, title: rendered.title, coverImage: nil)
        }
    }

    // MARK: Prepare

    /// What the renderer loads.
    struct Source: Sendable {
        var resources: any WebResourceProvider
        var mainPath: String
        /// Generated by the app (plain text, Markdown) rather than the reader's own HTML.
        var isGenerated: Bool
        var title: String?
        /// For an `.xhtml` file: serve it as HTML instead if it is not well-formed.
        var fallbackToHTML: WebFileResources?
    }

    /// Reads and decodes the file and builds what the renderer will load. Off the main thread.
    @concurrent
    static func prepare(_ input: ConversionInput) async throws -> Source {
        let data = try await WebConversion.readFile(input.original)
        guard !data.isEmpty else { throw ConversionError.failed(reason: "The file is empty.") }
        try Task.checkCancellation()
        switch input.format {
        case .plainText:
            guard let decoded = WebTextDecoding.decode(data) else {
                throw ConversionError.failed(reason: "The file does not contain text: it may not be a text file.")
            }
            guard !decoded.text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
                throw ConversionError.failed(reason: "The file has no text in it.")
            }
            let html = PlainTextHTML.html(decoded.text, title: nil)
            return generated(html, title: nil)
        case .markdown:
            guard let decoded = WebTextDecoding.decode(data) else {
                throw ConversionError.failed(reason: "The file does not contain text: it may not be a Markdown file.")
            }
            guard !decoded.text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
                throw ConversionError.failed(reason: "The file has no text in it.")
            }
            let result: MarkdownHTML.Result
            do {
                result = try MarkdownHTML.html(decoded.text)
            } catch {
                throw ConversionError.failed(reason: "The Markdown could not be read (\(error.localizedDescription)).")
            }
            let html = PlainTextHTML.document(body: result.html, title: result.title, bodyClass: "tt-markdown")
            return generated(html, title: result.title)
        case .html:
            // A text file has no NUL bytes (UTF-16 aside); binary data named .html would lay out as junk.
            guard WebTextDecoding.decode(data) != nil else {
                throw ConversionError.failed(reason: "The file does not contain text: it may not be an HTML file.")
            }
            let isXHTML = ["xhtml", "xht"].contains(input.original.pathExtension.lowercased())
                || ["xhtml", "xht"].contains((input.fileName as NSString).pathExtension.lowercased())
            let mime = isXHTML ? "application/xhtml+xml" : "text/html"
            // Say UTF-8 unless the file names its own character set or is not UTF-8.
            let encoding: String? = WebTextDecoding.declaresCharset(data) || String(data: data, encoding: .utf8) == nil ? nil : "utf-8"
            let path = isXHTML ? "document.xhtml" : "document.html"
            let entry = WebFileResources.Entry(source: .data(data), mimeType: mime, textEncodingName: encoding)
            let resources = WebFileResources([path: entry])
            var fallback: WebFileResources?
            if isXHTML {
                fallback = WebFileResources([path: WebFileResources.Entry(source: .data(data), mimeType: "text/html", textEncodingName: encoding)])
            }
            return Source(resources: resources, mainPath: path, isGenerated: false, title: nil, fallbackToHTML: fallback)
        case .webArchive:
            let archive: WebArchiveResources
            do {
                archive = try WebArchiveResources(data: data)
            } catch {
                throw ConversionError.failed(reason: "The web archive could not be read: it is damaged or not a Safari web archive.")
            }
            return Source(resources: archive, mainPath: archive.mainPath, isGenerated: false, title: nil, fallbackToHTML: nil)
        default:
            throw ConversionError.unsupported(reason: "This converter does not handle \(input.format.rawValue) files.")
        }
    }

    private static func generated(_ html: String, title: String?) -> Source {
        let resources = WebFileResources(["document.html": .init(source: .data(Data(html.utf8)), mimeType: "text/html", textEncodingName: "utf-8")])
        return Source(resources: resources, mainPath: "document.html", isGenerated: true, title: title, fallbackToHTML: nil)
    }
}

// MARK: - Style

/// The app's typography for documents it sets itself (plain text, Markdown), and the defaults an
/// HTML file falls back on. Every rule is wrapped in `:where()` so it has no specificity: a
/// document's own CSS always wins. Sizes are relative to the root size `EPUBStyle` sets.
nonisolated enum TextDocumentStyle {
    static let css = """
        :where(body) { font-family: "Iowan Old Style", Palatino, Georgia, serif; }
        :where(h1, h2, h3, h4, h5, h6) { font-family: -apple-system, "Helvetica Neue", Helvetica, sans-serif; \
        line-height: 1.2; margin: 1.1em 0 0.45em; }
        :where(h1) { font-size: 1.75em; } :where(h2) { font-size: 1.4em; } :where(h3) { font-size: 1.18em; }
        :where(h4) { font-size: 1.05em; } :where(h5, h6) { font-size: 1em; }
        :where(p) { margin: 0 0 0.65em; }
        :where(li > p) { margin: 0 0 0.2em; }
        :where(ul, ol) { padding-left: 1.5em; margin: 0 0 0.65em; }
        :where(pre, code, kbd, samp, tt) { font-family: Menlo, "SF Mono", Courier, monospace; font-size: 0.88em; }
        :where(pre) { white-space: pre-wrap; overflow-wrap: anywhere; margin: 0 0 0.8em; padding: 0.5em 0.7em; \
        background: #f3f3f1; border-radius: 3px; -webkit-print-color-adjust: exact; print-color-adjust: exact; }
        :where(pre code) { font-size: 1em; }
        :where(blockquote) { margin: 0 0 0.8em; padding-left: 0.9em; border-left: 3px solid #c8c8c8; color: #3a3a3a; }
        :where(table) { border-collapse: collapse; margin: 0 0 0.8em; font-size: 0.92em; }
        :where(th, td) { border: 0.5px solid #9a9a9a; padding: 0.25em 0.5em; vertical-align: top; text-align: left; }
        :where(th) { background: #eeeeec; -webkit-print-color-adjust: exact; print-color-adjust: exact; }
        :where(hr) { border: 0; border-top: 1px solid #b4b4b4; margin: 1.2em 0; }
        :where(a) { color: #1d4f99; }
        .tt-image-alt { font-style: italic; color: #666; }
        .tt-plain p { white-space: normal; }
        .tt-plain p.tt-cont { margin-bottom: 0; }
        .tt-pre { white-space: pre-wrap; overflow-wrap: anywhere; font-family: Menlo, "SF Mono", Courier, monospace; \
        font-size: 0.85em; margin: 0; padding: 0; background: none; }
        """

    static func styleSheet(textSize: ConversionTextSize, printableHeight: CGFloat) -> String {
        EPUBStyle.styleSheet(textSize: textSize, printableHeight: printableHeight) + "\n" + css
    }
}

// MARK: - Printing

@MainActor
enum TextDocumentPrinter {
    struct Rendered {
        var parts: [WebPrintedPart]
        var title: String?
    }

    static func print(_ source: TextDocumentConverter.Source, textSize: ConversionTextSize, workspace: URL,
                      timeout: TimeInterval, diagnostics: WebConversionDiagnostics?,
                      trace: (@Sendable (String) -> Void)?, progress: @escaping (Double) -> Void) async throws -> Rendered {
        var configuration = WebPDFRenderer.Configuration(pageSize: ConversionOptions.reflowPageSize, margins: EPUBStyle.margins)
        configuration.styleSheet = TextDocumentStyle.styleSheet(textSize: textSize, printableHeight: configuration.printableRect.height)
        configuration.loadTimeout = timeout
        configuration.trace = trace
        var renderer = WebPDFRenderer(provider: source.resources, configuration: configuration)
        defer { renderer.tearDown() }
        let started = CACurrentMediaTime()
        try await renderer.start()
        let report = try await renderer.load(path: source.mainPath)
        if report.hasParserError, let fallback = source.fallbackToHTML {
            renderer.tearDown()
            renderer = WebPDFRenderer(provider: fallback, configuration: configuration)
            try await renderer.start()
            try await renderer.load(path: source.mainPath)
            diagnostics?.note("not well-formed XHTML: laid out as HTML")
        }
        diagnostics?.record(loadSeconds: CACurrentMediaTime() - started)
        progress(0.15)
        let content = try await WebPageContent.check(renderer)
        if content.isEmpty {
            throw ConversionError.failed(reason: "The file shows no text or pictures, so there is nothing to convert.")
        }
        let title = source.title ?? [content.title, content.firstHeading].first { !$0.isEmpty }
        let parts = try await renderer.printSegments(path: source.mainPath, into: workspace, prefix: "part", headings: true,
                                                     progress: { progress(0.15 + 0.85 * $0) })
        diagnostics?.record(parts: parts)
        diagnostics?.record(requests: renderer.schemeHandler.records)
        diagnostics?.record(pageSize: renderer.configuration.pageSize, margins: renderer.configuration.margins)
        return Rendered(parts: parts, title: title)
    }
}
