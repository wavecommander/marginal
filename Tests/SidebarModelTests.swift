/// Helpers for the WP5 sidebar tests that need a real session.
@MainActor
enum SidebarTestSupport {
    static let repoRoot = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()

    /// The `large.pdf` fixture's outline shape: 15 chapters × 6 sections × 3 subsections (375).
    /// The same builder as `ContentsTreeTests.largeOutline` in ReaderCore's tests.
    static func largeOutline(userHeadings: [UserHeading] = []) -> Outline {
        var entries: [RawOutlineEntry] = []
        for c in 0..<15 {
            let cStart = c * 100
            entries.append(RawOutlineEntry(title: "\(c + 1) Chapter", level: 1, pageIndex: cStart))
            for s in 0..<6 {
                let sStart = cStart + s * 16 + 1
                entries.append(RawOutlineEntry(title: "\(c + 1).\(s + 1) Section", level: 2, pageIndex: sStart))
                for u in 0..<3 {
                    entries.append(RawOutlineEntry(title: "\(c + 1).\(s + 1).\(u + 1) Sub", level: 3, pageIndex: sStart + u * 4 + 1))
                }
            }
        }
        return Outline(pdfEntries: entries, userHeadings: userHeadings, pageCount: 1500)
    }

    struct Fixture {
        let store: LibraryStore
        let book: Book
    }

    /// An ephemeral store with one book copied from `Fixtures/out/<file>` (generated by
    /// `scripts/test.sh`). `small.pdf`: 12 pages, "1 Linear Systems" p1 (1.1 p2, 1.2 p4),
    /// "2 Vector Spaces" p5 (2.1 p6, 2.2 p8), "3 Eigenvalues" p9 (3.1 p10, 3.2 p12).
    /// `no-outline.pdf`: 40 pages, no outline.
    static func makeFixture(_ file: String = "small.pdf", pageCount: Int = 12) throws -> Fixture {
        let source = repoRoot.appendingPathComponent("Fixtures/out/\(file)")
        let store = try LibraryStore.ephemeral()
        let book = Book(title: file, fingerprint: "sidebar-test-\(UUID().uuidString)", fileName: file,
                        pageCount: pageCount, fileSize: 1)
        try store.books.save(book)
        let url = store.documentURL(for: book)
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try FileManager.default.copyItem(at: source, to: url)
        return Fixture(store: store, book: book)
    }

    static func makeSession(_ fixture: Fixture) -> ReaderSession {
        var configuration = ReaderSession.Configuration()
        configuration.lastReadSaveDelay = .milliseconds(100)
        configuration.notebookRebuildDelay = .milliseconds(10)
        configuration.installsFeatures = false
        return ReaderSession(book: fixture.book, store: fixture.store, configuration: configuration)
    }

    /// An opened session with its outline loaded and a started sidebar model.
    static func openedSession(_ fixture: Fixture) async -> (ReaderSession, ContentsSidebarModel) {
        let session = makeSession(fixture)
        session.open()
        _ = await waitUntil { session.isOutlineLoaded }
        let model = ContentsSidebarModel.shared(for: session)
        return (session, model)
    }

    static func waitUntil(timeout: Double = 5, _ condition: () -> Bool) async -> Bool {
        let deadline = Date().addingTimeInterval(timeout)
        while !condition() {
            if Date() > deadline { return false }
            try? await Task.sleep(for: .milliseconds(20))
        }
        return true
    }

    /// Lets observation callbacks (scheduled on the next main-actor turn) run.
    static func settle() async {
        for _ in 0..<5 { await Task.yield() }
        try? await Task.sleep(for: .milliseconds(30))
    }

    static func cleanUp(_ fixture: Fixture) {
        try? FileManager.default.removeItem(at: fixture.store.rootDirectory)
    }

    static func row(_ model: ContentsSidebarModel, _ title: String) -> ContentsRow? {
        model.rows.first { $0.node.title == title }
    }

    /// Collapses every top-level heading (undoing the default expansion `small.pdf`'s three
    /// chapters get).
    static func collapseAll(_ model: ContentsSidebarModel) {
        for row in model.rows where row.depth == 0 && row.isExpanded { model.toggle(row.anchor) }
    }
}

/// WP5: the sidebar model against a real session: rows, current-section tracking and the follow
/// rule, badges, bookmarks, changes from another window.
@MainActor
struct SidebarModelTests {
    typealias Support = SidebarTestSupport

    @Test func rowsAndCurrentSectionFollowTheSession() async throws {
        let fixture = try Support.makeFixture()
        defer { Support.cleanUp(fixture) }
        let (session, model) = await Support.openedSession(fixture)
        await Support.settle()
        // Three chapters are a short top level: the default expansion opens them.
        #expect(model.rows.count == 9)
        Support.collapseAll(model)

        // Page 1 is in "1 Linear Systems": its chapter is the current row (no children opened,
        // since the deepest heading is the chapter itself).
        #expect(model.rows.map(\.node.title) == ["1 Linear Systems", "2 Vector Spaces", "3 Eigenvalues"])
        #expect(model.currentRow == Support.row(model, "1 Linear Systems")?.anchor)

        // A jump (records history) into 2.1 follows: chapter 2 opens, 2.1 is current, and the
        // list is asked to scroll to it (it is not on screen yet).
        #expect(session.jump(toPage: 6))
        await Support.settle()
        #expect(model.rows.map(\.node.title) == ["1 Linear Systems", "2 Vector Spaces", "2.1 Foundations",
                                                  "2.2 Exercises", "3 Eigenvalues"])
        #expect(model.currentRow == Support.row(model, "2.1 Foundations")?.anchor)
        #expect(model.currentPath == Set(session.headingPath.map(\.anchor)))
        #expect(model.scrollRequest?.anchor == model.currentRow)
    }

    @Test func scrollingFollowsOnlyWhileTheCurrentRowIsOnScreen() async throws {
        let fixture = try Support.makeFixture()
        defer { Support.cleanUp(fixture) }
        let (session, model) = await Support.openedSession(fixture)
        await Support.settle()
        Support.collapseAll(model)
        // The list shows every row.
        for row in model.rows { model.rowAppeared(row.anchor) }

        // Scrolling the book (not a jump) from chapter 1 into 2.1: the previous current row was on
        // screen, so the list follows (chapter 2 opens).
        session.pdfReportedCurrentPage(6)
        await Support.settle()
        let s21 = try #require(Support.row(model, "2.1 Foundations"))
        #expect(model.currentRow == s21.anchor)
        for row in model.rows { model.rowAppeared(row.anchor) }
        let requestsBefore = model.scrollRequest

        // The reader scrolls the sidebar so 2.1 is off screen, then scrolls the book on into
        // chapter 3: the marking moves but nothing opens and the list is not scrolled.
        model.rowDisappeared(s21.anchor)
        session.pdfReportedCurrentPage(8)
        await Support.settle()
        #expect(model.currentRow == Support.row(model, "3 Eigenvalues")?.anchor)
        #expect(Support.row(model, "3 Eigenvalues")?.isExpanded == false)
        #expect(Support.row(model, "2 Vector Spaces")?.isExpanded == true)
        #expect(model.scrollRequest == requestsBefore)

        // A jump follows again, wherever the sidebar is.
        session.jump(toPage: 11)
        await Support.settle()
        #expect(Support.row(model, "3 Eigenvalues")?.isExpanded == true)
        #expect(model.currentRow == Support.row(model, "3.2 Exercises")?.anchor)
        #expect(model.scrollRequest != requestsBefore)
        #expect(model.scrollRequest?.anchor == model.currentRow)
    }

    @Test func toggleAndManualCollapseOfTheCurrentBranch() async throws {
        let fixture = try Support.makeFixture()
        defer { Support.cleanUp(fixture) }
        let (session, model) = await Support.openedSession(fixture)
        await Support.settle()
        Support.collapseAll(model)
        session.jump(toPage: 6)
        await Support.settle()
        let chapter2 = try #require(Support.row(model, "2 Vector Spaces"))
        #expect(chapter2.isExpanded)
        // Collapsing the branch with the current section moves the marking to the chapter.
        model.toggle(chapter2.anchor)
        #expect(Support.row(model, "2.1 Foundations") == nil)
        #expect(model.currentRow == chapter2.anchor)
        #expect(model.currentPath.contains(chapter2.anchor))
        // Expansion is per window: a second session on the same book has its own.
        let other = Support.makeSession(fixture)
        other.open()
        _ = await Support.waitUntil { other.isOutlineLoaded }
        let otherModel = ContentsSidebarModel.shared(for: other)
        await Support.settle()
        #expect(otherModel !== model)
        let chapter3 = try #require(Support.row(model, "3 Eigenvalues"))
        model.toggle(chapter3.anchor)
        #expect(Support.row(model, "3 Eigenvalues")?.isExpanded == true)
        #expect(Support.row(otherModel, "3 Eigenvalues")?.isExpanded == true)  // its default
        otherModel.toggle(chapter3.anchor)
        #expect(Support.row(otherModel, "3 Eigenvalues")?.isExpanded == false)
        #expect(Support.row(model, "3 Eigenvalues")?.isExpanded == true)
    }

    @Test func badgesComeFromNotesAndHighlightsButNotBookmarks() async throws {
        let fixture = try Support.makeFixture()
        defer { Support.cleanUp(fixture) }
        let (session, model) = await Support.openedSession(fixture)
        _ = await Support.waitUntil { session.notebook != nil }
        let anchors = Dictionary(uniqueKeysWithValues: session.outline.nodes.map { ($0.title, $0.anchor) })
        #expect(session.notebook?.badgedAnchors.isEmpty == true)

        // A bookmark never badges.
        BookmarkActions.setBookmarked(true, page: 9, session: session)
        // A page note on page 7 (2.1) badges 2.1 and its chapter, not 2.2 or chapter 1.
        try session.perform { _ = try $0.notes.save(Note(bookID: fixture.book.id, target: .page(6), text: "A note")) }
        // A highlight on page 12 (3.2) badges 3.2 and chapter 3.
        try session.perform {
            try $0.highlights.save(Highlight(bookID: fixture.book.id, pageIndex: 11, rects: [], color: .yellow, text: "x"))
        }
        // A heading note on "1.2 Exercises".
        try session.perform {
            _ = try $0.notes.save(Note(bookID: fixture.book.id, target: .heading(anchors["1.2 Exercises"]!), text: "Section"))
        }
        #expect(await Support.waitUntil { session.notebook?.badgedAnchors.count == 6 })
        let notebook = try #require(session.notebook)
        for title in ["2 Vector Spaces", "2.1 Foundations", "3 Eigenvalues", "3.2 Exercises", "1 Linear Systems", "1.2 Exercises"] {
            #expect(notebook.hasBadge(anchors[title]!), "\(title) should have a badge")
        }
        for title in ["2.2 Exercises", "3.1 Foundations", "1.1 Foundations"] {
            #expect(!notebook.hasBadge(anchors[title]!), "\(title) should not have a badge")
        }
        #expect(notebook.counts(for: anchors["2 Vector Spaces"]!).pageNotes == 1)

        // Page marks for the Pages grid.
        await Support.settle()
        #expect(model.pageMarks[6] == .note)
        #expect(model.pageMarks[11] == .highlight)
        #expect(model.pageMarks[9] == nil)
        #expect(model.bookmarkedPages == [9])
    }

    @Test func changesFromAnotherWindowAppear() async throws {
        let fixture = try Support.makeFixture()
        defer { Support.cleanUp(fixture) }
        let (session, model) = await Support.openedSession(fixture)
        let otherWindow = ChangeOrigin(label: "other window")

        // Bookmarks, out of order, from another origin.
        try fixture.store.perform(as: otherWindow) {
            try fixture.store.bookmarks.setBookmarked(true, bookID: fixture.book.id, pageIndex: 8)
            try fixture.store.bookmarks.setBookmarked(true, bookID: fixture.book.id, pageIndex: 2)
            try fixture.store.bookmarks.setBookmarked(true, bookID: fixture.book.id, pageIndex: 5)
        }
        #expect(await Support.waitUntil { model.bookmarks.count == 3 })
        #expect(model.bookmarks.map(\.pageIndex) == [2, 5, 8])

        // A user heading added in another window appears in this window's Contents.
        let heading = UserHeading(bookID: fixture.book.id, title: "Elsewhere", pageIndex: 10, parent: nil)
        try fixture.store.perform(as: otherWindow) { try fixture.store.headings.save(heading) }
        #expect(await Support.waitUntil { Support.row(model, "Elsewhere") != nil })
        _ = session
    }

    @Test func bookmarkOrderingIsByPageAndUnique() {
        let bookID = UUID()
        let t = Date(timeIntervalSinceReferenceDate: 0)
        let list = [
            Bookmark(bookID: bookID, pageIndex: 30, createdAt: t),
            Bookmark(bookID: bookID, pageIndex: 3, createdAt: t.addingTimeInterval(5)),
            Bookmark(bookID: bookID, pageIndex: 12, createdAt: t.addingTimeInterval(1)),
            Bookmark(bookID: bookID, pageIndex: 3, createdAt: t.addingTimeInterval(2)),
        ]
        let sorted = ContentsSidebarModel.sortedBookmarks(list)
        #expect(sorted.map(\.pageIndex) == [3, 12, 30])
        #expect(sorted[0].createdAt == t.addingTimeInterval(2))
    }

    @Test func memoryWarningPurgesThumbnails() async throws {
        let fixture = try Support.makeFixture()
        defer { Support.cleanUp(fixture) }
        let (session, model) = await Support.openedSession(fixture)
        let image = await model.thumbnails.image(forPage: 0, size: CGSize(width: 60, height: 80), scale: 1)
        #expect(image != nil)
        #expect(model.thumbnails.cachedCount == 1)
        session.handleMemoryWarning()
        #expect(await Support.waitUntil { model.thumbnails.cachedCount == 0 })
        #expect(model.thumbnails.stats.purges == 1)
    }
}
